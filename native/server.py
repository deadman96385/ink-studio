def number(value, low, high, label):
    try:
        n = float(value)
    except (ValueError, TypeError):
        raise ValueError(f'{label} must be a number.')
    if not math.isfinite(n) or not low <= n <= high:
        raise ValueError(f'{label} must be between {low:g} and {high:g}.')
    return n


def color(value):
    if not isinstance(value, str) or not re.fullmatch(r'#[0-9a-fA-F]{6}', value):
        raise ValueError('Choose a six-digit thread color.')
    return value.lower()


def safe_id(value):
    if not isinstance(value, str) or not re.fullmatch(r'[a-zA-Z0-9_-]{1,80}', value):
        raise ValueError('Invalid item identifier.')
    return value


def write_atomic(path, data):
    tmp = path.with_name(path.name + '.' + uuid.uuid4().hex + '.tmp')
    tmp.write_text(json.dumps(data, ensure_ascii=False), encoding='utf-8')
    tmp.replace(path)


def svg_root(w=100,h=100):
    w,h=f'{w:g}',f'{h:g}'
    root=ET.Element(f'{{{SVG}}}svg', nsmap={None: SVG, 'inkscape': INK, 'inkstitch': STITCH},
                    width=f'{w}mm', height=f'{h}mm', viewBox=f'0 0 {w} {h}', version='1.1')
    return root


def xml(data):
    if len(data) > MAX_BODY or b'<!DOCTYPE' in data.upper() or b'<!ENTITY' in data.upper():
        raise ValueError('This SVG contains unsupported document declarations.')
    return ET.fromstring(data, parser=ET.XMLParser(resolve_entities=False, no_network=True,
                                                 remove_comments=True, remove_pis=True))


def run(args, timeout=180, headless=False):
    if args[0]==ENGINE and any(v in args for v in ('--extension=output','--extension=stitch_plan_preview','--extension=png_simple','--extension=png_realistic')) and str(args[-1]).endswith('.svg'):
        if svg_structure.has_masks(xml(Path(args[-1]).read_bytes())):raise ValueError('Use Digitize → Prepare SVG artwork to convert opacity masks before generating stitches. Choose a mask cutoff and preview the boundary.')
    return studio_runtime.execute(args,timeout=timeout,headless=headless)


def bounds(path,sewing=False):
    # query-all reports px irrespective of the SVG's mm viewBox.
    if sewing:
        measured=xml(Path(path).read_bytes());command_symbols.hide(measured);command_symbols.hide_ignored(measured);marker_symbols.hide(measured)
        with tempfile.TemporaryDirectory(prefix='sewing-bounds-') as tmp:
            file=Path(tmp)/'bounds.svg';file.write_bytes(ET.tostring(measured))
            raw=run(['inkscape',str(file),'--query-all'],40).decode()
    else:raw = run(['inkscape', str(path), '--query-all'], 40).decode()
    for line in raw.splitlines():
        fields = line.split(',')
        if len(fields) == 5:
            vals = [float(x) * PX_MM for x in fields[1:]]
            if all(math.isfinite(v) for v in vals) and vals[2] > 0 and vals[3] > 0:
                return vals
    raise ValueError('This design has no visible embroidery shapes.')


