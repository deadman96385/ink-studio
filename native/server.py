def import_svg(data):
    raw = str(data.get('svg', '')).encode()
    # Older Ink/Stitch files are upgraded first; build_svg stamps version 4.
    raw, svg_update = svg_upgrade.upgrade(raw, sys.modules[__name__], data.get('updateFrom', 'auto'))
    source_preferences=preferences.imported(xml(raw))
    source_grids=crossstitch.imported_grids(xml(raw),sys.modules[__name__])
    root = sanitize_svg(raw)
    with ENGINE_LOCK, tempfile.TemporaryDirectory(prefix='import-') as tmp:
        p = Path(tmp) / 'import.svg'; p.write_bytes(ET.tostring(root))
        # Inkscape resolves original viewBox units and transforms while
        # converting supported primitives to paths, preserving stitch params.
        run(['inkscape', str(p), '--export-text-to-path',
             '--export-filename=' + str(Path(tmp) / 'normalized.svg')])
        normalized = Path(tmp) / 'normalized.svg'
        doc = sanitize_svg(normalized.read_bytes())
        # Embed the original SVG in a 100mm document with an explicit px size.
        # Its viewport/viewBox mapping stays intact, including nested transforms.
        def px_length(value, default):
            match = re.fullmatch(r'\s*([0-9.+-]+)(mm|cm|in|pt|pc|px)?\s*', value or '')
            if not match:
                return default
            factors = {'mm': 96/25.4, 'cm': 96/2.54, 'in': 96, 'pt': 96/72, 'pc': 16, 'px': 1, None: 1}
            return float(match[1]) * factors[match[2]]
        vb = [float(v) for v in re.split(r'[ ,]+', doc.get('viewBox', '0 0 300 150').strip())]
        pw = px_length(doc.get('width'), vb[2]); ph = px_length(doc.get('height'), vb[3])
        if len(vb) != 4 or vb[2] <= 0 or vb[3] <= 0 or pw <= 0 or ph <= 0:
            raise ValueError('The SVG needs a positive viewport size.')
        sx, sy = pw * PX_MM / vb[2], ph * PX_MM / vb[3]
        svg_masks.freeze_viewport(doc,vb[2],vb[3])
        aspect = doc.get('preserveAspectRatio', 'xMidYMid meet')
        ox = oy = 0
        if aspect != 'none':
            uniform = max(sx, sy) if 'slice' in aspect else min(sx, sy)
            extra_x, extra_y = pw * PX_MM - vb[2] * uniform, ph * PX_MM - vb[3] * uniform
            ox = extra_x if 'xMax' in aspect else 0 if 'xMin' in aspect else extra_x / 2
            oy = extra_y if 'YMax' in aspect else 0 if 'YMin' in aspect else extra_y / 2
            sx = sy = uniform
        outer = svg_root()
        g = ET.SubElement(outer, f'{{{SVG}}}g', transform=f'translate({ox},{oy}) scale({sx},{sy}) translate({-vb[0]},{-vb[1]})')
        inherited = ET.SubElement(g, f'{{{SVG}}}g')
        for name, value in doc.attrib.items():
            if ET.QName(name).localname not in ('width', 'height', 'viewBox', 'version', 'id', 'x', 'y', 'preserveAspectRatio'):
                inherited.set(name, value)
        for child in doc:
            inherited.append(copy.deepcopy(child))
        measured=copy.deepcopy(outer);command_symbols.hide(measured);marker_symbols.hide(measured)
        p.write_bytes(ET.tostring(measured))
        x, y, w, h = bounds(p)
        normalized_group = ET.Element(f'{{{SVG}}}g', nsmap=NS, transform=f'translate({-x},{-y})')
        normalized_group.append(g)
        svg = ET.tostring(normalized_group, encoding='unicode')
        key = hashlib.sha256(svg.encode()).hexdigest()
        result = {'key': key, 'width': w, 'height': h, 'svg': svg,
                  'name': str(data.get('name', 'Imported design'))[:100]}
        result['svgFeatures']=svg_structure.features(doc)
        if svg_update:result['svgUpdate']=svg_update
        if source_preferences is not None:result['embroiderySettings']=source_preferences
        if source_grids:
            result['crossGrids']=source_grids
            if x>=-.1 and y>=-.1 and x+w<=100.1 and y+h<=100.1:result['placement']={'x':x,'y':y}
        write_atomic(DATA / 'assets' / (key + '.json'), result)
        return result


def asset_layers(project):
    def walk(layer,depth=0):
        if depth>10:raise ValueError('This project contains too many nested lettering guides.')
        yield layer
        source=layer.get('curveSource',{})
        if isinstance(source,dict):
            for key in ('textLayer','guideLayer'):
                if isinstance(source.get(key),dict):yield from walk(source[key],depth+1)
    for layer in project.get('layers',[]):yield from walk(layer)


