def lettering_settings(data):
    font = FONTS.get(data.get('font'))
    if not font:
        raise ValueError('Choose an installed embroidery font.')
    text = unicodedata.normalize('NFC', str(data.get('text', '')).replace('\r', ''))
    if not text.strip() or len(text) > 180 or len(text.splitlines()) > 12:
        raise ValueError('Enter 1–180 characters, on up to 12 lines.')
    if font['case'] == 'upper':
        text = text.upper()
    elif font['case'] == 'lower':
        text = text.lower()
    # Reject missing characters rather than silently substituting glyphs.
    available = set(''.join(font['glyphs']))
    missing = sorted({c for c in text if not c.isspace() and c not in available})
    if available and missing:
        raise ValueError(f"{font['name']} has no glyph for: {' '.join(missing)}")
    align = data.get('align', 'center')
    if align not in ('left', 'center', 'right','block','letterspacing'):
        raise ValueError('Choose left, center, right, or justified alignment.')
    scale = round(number(data.get('scale', 100), font['minScale'], font['maxScale'], 'Font scale'))
    spacing = number(data.get('lineSpacing', 0), -10, 30, 'Extra line spacing')
    letter_spacing = number(data.get('letterSpacing', 0), -2, 10, 'Extra letter spacing')
    word_spacing = number(data.get('wordSpacing', 0), -10, 30, 'Extra word spacing')
    trim=data.get('trim','line');color_sort=data.get('colorSort','off')
    if trim not in ('off','line','word','glyph'):raise ValueError('Choose no trims, or trim after each line, word or glyph.')
    if color_sort not in ('off','all','line','word'):raise ValueError('Choose a lettering color-sort scope.')
    if color_sort!='off' and not font['sortable']:raise ValueError('This font is not indexed for color sorting.')
    if font['leading'] * scale / 100 + spacing <= 0:
        raise ValueError('Line spacing must keep each line below the previous line.')
    settings=dict(font=font['id'], text=text, scale=scale, align=align,lineSpacing=spacing, letterSpacing=letter_spacing)
    # Keep the original cache identity for projects using the default options.
    if word_spacing:settings['wordSpacing']=word_spacing
    if trim!='line':settings['trim']=trim
    if color_sort!='off':settings['colorSort']=color_sort
    symbols=data.get('commandSymbols',False)
    if type(symbols) is not bool:raise ValueError('Choose whether trims use command symbols.')
    if symbols:settings['commandSymbols']=True
    return settings


def stitch_data(path,include_commands=False):
    pattern = pystitch.read(str(path))
    if not pattern or not pattern.stitches:
        raise ValueError('Ink/Stitch generated an empty embroidery file.')
    if len(pattern.stitches) > 400000:
        raise ValueError('This design exceeds the editor’s 400,000-command preview limit.')
    b = pattern.bounds()
    threads = [{'color': t.hex_color(), 'name': t.description or f'Thread {i + 1}', 'brand': t.brand or '', 'number': t.catalog_number or ''}
               for i, t in enumerate(pattern.threadlist)]
    segments = []
    previous = None
    thread = 0
    count = trims = jumps = stops = 0
    for x, y, command in pattern.stitches:
        command &= 255
        pos = [round(x / 10, 3), round(y / 10, 3)]
        if command == pystitch.STITCH:
            if previous is not None:
                segments.append([*previous, *pos, thread])
            count += 1
        elif command == pystitch.COLOR_CHANGE:
            thread += 1
        elif command == pystitch.TRIM:
            trims += 1
        elif command == pystitch.JUMP:
            jumps += 1
        elif command == pystitch.STOP:
            stops += 1
        previous = pos
    result = {'bounds': [v / 10 for v in b], 'width': (b[2] - b[0]) / 10,
            'height': (b[3] - b[1]) / 10, 'stitches': count, 'trims': trims,
            'jumps': jumps, 'stops': stops, 'colorChanges':thread, 'threads': threads, 'segments': segments}
    if include_commands:
        result['commands']=[[round(x/10,3),round(y/10,3),command&255] for x,y,command in pattern.stitches]
        result['commandTypes']={name:getattr(pystitch,key) for name,key in [('stitch','STITCH'),('jump','JUMP'),('trim','TRIM'),('stop','STOP'),('color','COLOR_CHANGE'),('end','END')]}
    return result


