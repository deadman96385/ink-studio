def prefix_ids(node, prefix):
    # Ink/Stitch recognizes command/marker definitions by their ID prefix.
    mapping = {e.get('id'): prefix + e.get('id') for e in node.iter() if e.get('id') and not
               (ET.QName(e).localname in ('marker','symbol') and e.get('id').startswith(('inkstitch-','inkstitch_')))}
    for e in node.iter():
        if e.get('id') in mapping:
            e.set('id', mapping[e.get('id')])
        for name, value in list(e.attrib.items()):
            value = re.sub(r'url\(#([^)]*)\)', lambda m: 'url(#' + mapping.get(m[1], m[1]) + ')', value)
            if value.startswith('#') and value[1:] in mapping:
                value = '#' + mapping[value[1:]]
            e.set(name, value)


def paint(node, value):
    for e in node.iter():
        if ET.QName(e).localname not in ('path', 'rect', 'ellipse', 'circle', 'polygon', 'polyline', 'line'):
            continue
        style = {k.strip().lower(): v.strip() for k, v in (part.split(':', 1) for part in e.get('style', '').split(';') if ':' in part)}
        for key in ('fill', 'stroke'):
            existing = None
            for ancestor in [e, *e.iterancestors()]:
                inherited = {k.strip().lower(): v.strip() for k, v in (part.split(':', 1) for part in ancestor.get('style', '').split(';') if ':' in part)}
                candidate = inherited.get(key, ancestor.get(key))
                if candidate and candidate.strip() != 'inherit':
                    existing = candidate.strip()
                    break
            existing = existing or ('black' if key == 'fill' else 'none')
            if existing != 'none':
                style[key] = value
                e.set(key, value)
        e.set('style', ';'.join(k + ':' + v for k, v in style.items()))


def stroke_scale(node):
    """Mean transformed axis scale, in the exported SVG's millimeter units.

    Ink/Stitch uses the same mean-axis convention for nonuniform scaling.
    Translations and rotation centers don't change the linear component.
    """
    def multiply(a, b):
        return (a[0]*b[0]+a[2]*b[1], a[1]*b[0]+a[3]*b[1],
                a[0]*b[2]+a[2]*b[3], a[1]*b[2]+a[3]*b[3])
    matrix = (1, 0, 0, 1)
    for ancestor in reversed([node, *node.iterancestors()]):
        for name, args in re.findall(r'([A-Za-z]+)\s*\(([^)]*)\)', ancestor.get('transform', '')):
            vals = [float(v) for v in re.findall(r'[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?', args)]
            if name == 'translate':
                continue
            if name == 'matrix' and len(vals) == 6:
                transform = tuple(vals[:4])
            elif name == 'scale' and len(vals) in (1, 2):
                transform = (vals[0], 0, 0, vals[-1])
            elif name == 'rotate' and len(vals) in (1, 3):
                c, s = math.cos(math.radians(vals[0])), math.sin(math.radians(vals[0]))
                transform = (c, s, -s, c)
            elif name in ('skewX', 'skewY') and len(vals) == 1:
                tangent = math.tan(math.radians(vals[0]))
                transform = (1, 0, tangent, 1) if name == 'skewX' else (1, tangent, 0, 1)
            else:
                raise ValueError('This SVG has an unsupported transform. Flatten its transforms before changing stitch settings.')
            matrix = multiply(matrix, transform)
    scale = (math.hypot(matrix[0], matrix[1]) + math.hypot(matrix[2], matrix[3])) / 2
    if not math.isfinite(scale) or scale < .000001:
        raise ValueError('This SVG contains a collapsed transform.')
    return scale


def stitch_settings(node, layer):
    mode = layer.get('stitch', 'fill')
    if mode not in ('fill', 'running', 'bean', 'zigzag', 'satin', 'original', 'ripple', 'manual'):
        raise ValueError('Unknown stitch type.')
    spacing = number(layer.get('spacing', .4), .2, 2, 'Row spacing')
    angle = number(layer.get('angle', 45), -180, 180, 'Fill angle')
    length = number(layer.get('stitchLength', 2.5), .5, 6, 'Stitch length')
    underlay = bool(layer.get('underlay', True))
    for e in node.iter():
        if ET.QName(e).localname not in ('path', 'rect', 'ellipse', 'circle', 'polygon', 'polyline', 'line'):
            continue
        if mode == 'original':
            continue
        for name in list(e.attrib):
            if name.startswith('{' + STITCH + '}'):
                del e.attrib[name]
        if mode == 'fill':
            e.set('style', f'fill:{color(layer["color"])};stroke:none')
            method=layer.get('fillMethod','tatami_fill')
            if method not in ('tatami_fill','contour_fill','circular_fill','meander_fill','cross_stitch','legacy_fill','linear_gradient_fill','tartan_fill','guided_fill','streamline_fill','wave_fill'):raise ValueError('Unknown fill method.')
            params = dict(fill_method=method, row_spacing_mm=spacing, angle=angle,
                          max_stitch_length_mm=length, fill_underlay=str(underlay),
                          fill_underlay_row_spacing_mm=number(layer.get('underlaySpacing', max(1.2, spacing * 3)), .4, 5, 'Underlay spacing'),
                          fill_underlay_inset_mm=number(layer.get('underlayInset', 0), 0, 3, 'Underlay inset'),
                          pull_compensation_mm=number(layer.get('pullCompensation', 0), 0, 1, 'Pull compensation'))
            if method in ('meander_fill','circular_fill'):params['running_stitch_length_mm']=length
        elif mode == 'satin':
            e.set('style',f'fill:none;stroke:{color(layer["color"])};stroke-width:.3')
            params=dict(satin_column='True',zigzag_spacing_mm=spacing,
                        max_stitch_length_mm=number(layer.get('satinMaxLength',6),1,12,'Maximum satin length'),
                        pull_compensation_mm=number(layer.get('pullCompensation',0),0,1,'Pull compensation'),
                        center_walk_underlay=str(bool(layer.get('satinCenter',True))),
                        contour_underlay=str(bool(layer.get('satinContour',False))),
                        zigzag_underlay=str(bool(layer.get('satinZigzag',False))),
                        start_at_nearest_point=str(bool(layer.get('nearestStart',True))),
                        end_at_nearest_point=str(bool(layer.get('nearestEnd',True))))
        else:
            width = number(layer.get('strokeWidth', 1.5), .3, 6, 'Zigzag width') if mode == 'zigzag' else .3
            e.set('style', f'fill:none;stroke:{color(layer["color"])};stroke-width:{width / stroke_scale(e)}')
            params = dict(stroke_method={'zigzag':'zigzag_stitch','ripple':'ripple_stitch','manual':'manual_stitch'}.get(mode,'running_stitch'),
                          running_stitch_length_mm=length, bean_stitch_repeats='1' if mode == 'bean' else '0',
                          zigzag_spacing_mm=spacing)
        params['trim_after'] = str(bool(layer.get('trimAfter', True)))
        for k, v in params.items():
            e.set(f'{{{STITCH}}}{k}', str(v))


def shape_path(layer,helper_mode=False,max_size=100):
    w = number(layer.get('width'), .2, 10000 if helper_mode else max_size, 'Width')
    h = number(layer.get('height'), .2, 10000 if helper_mode else max_size, 'Height')
    kind = layer['type']
    if kind == 'path' and layer.get('contours'):
        d=contour_d(layer['contours'],w,h)
    elif kind == 'ellipse':
        d = f'M 0,{h/2} A {w/2},{h/2} 0 1 0 {w},{h/2} A {w/2},{h/2} 0 1 0 0,{h/2} Z'
    elif kind == 'path':
        points = layer.get('points', [])
        if not 2 <= len(points) <= 2500:
            raise ValueError('A drawn path needs 2–2,500 points.')
        coords = [(number(p[0], 0, 1, 'Path x') * w, number(p[1], 0, 1, 'Path y') * h) for p in points]
        d = 'M ' + ' L '.join(f'{x},{y}' for x, y in coords)
        if layer.get('closed') or layer.get('stitch') == 'fill':
            d += ' Z'
    else:
        r = min(number(layer.get('radius', 0), 0, 50, 'Corner radius'), w/2, h/2)
        d = (f'M {r},0 H {w-r} Q {w},0 {w},{r} V {h-r} Q {w},{h} {w-r},{h} '
             f'H {r} Q 0,{h} 0,{h-r} V {r} Q 0,0 {r},0 Z')
    e=ET.Element(f'{{{SVG}}}path', d=d)
    if kind=='path' and layer.get('contours') and any(n.get('mode') for c in layer['contours'] for n in c['nodes']):e.set('{'+SODIPODI+'}nodetypes',contour_node_types(layer['contours']))
    e.set('fill-rule','evenodd')
    if layer.get('stitch')=='original':
        e.set('fill-rule','evenodd' if layer.get('originalFillRule')=='evenodd' else 'nonzero')
        e.set('style',f'fill:{color(layer["color"]) if layer.get("originalFill",True) else "none"};stroke:{color(layer["color"]) if layer.get("originalStroke") else "none"};stroke-width:{number(layer.get("originalWidth",.3),.01,20,"Stroke width")}')
        for k,v in layer.get('originalParams',{}).items():
            if re.fullmatch(r'[a-zA-Z0-9_]+',k) and isinstance(v,(str,float,int,bool)):e.set(f'{{{STITCH}}}{k}',str(v))
    return e


def build_svg(project,helper_mode=False,sewing=False):
    from linked import resolve
    project=resolve(project,sys.modules[__name__])
    if not isinstance(project, dict) or project.get('version') != 1:
        raise ValueError('This project format is not supported.')
    covered_report=None;editable_project=project
    if sewing and project.get('sewingOptimization',{}).get('enabled',True) and project.get('sewingOptimization',{}).get('undersewDetails'):
        from covered_details import prepare as undersew_details
        project,covered_report=undersew_details(project,sys.modules[__name__])
    layers = project.get('layers', [])
    if not isinstance(layers, list) or len(layers) > MAX_LAYERS:
        raise ValueError(f'A project can contain up to {MAX_LAYERS} layers.')
    hoop_w,hoop_h=hoops.size(project);hoop_max=max(hoop_w,hoop_h)
    root = svg_root(hoop_w,hoop_h)
    if covered_report:
        root.set('data-covered-detail-study',json.dumps({**covered_report,'treatments':[{k:v for k,v in t.items()if k!='mask'}for t in covered_report['treatments']]}))
    ET.SubElement(root, f'{{{SVG}}}title').text = str(project.get('name', 'Untitled'))[:120]
    preferences.metadata(root,preferences.effective(project))
    crossstitch.append_grids(root,project,sys.modules[__name__])
    meta = root.find(f'{{{SVG}}}metadata')
    ET.SubElement(meta, f'{{{STITCH}}}inkstitch_svg_version').text = '4'
    visible = 0
    for i, layer in enumerate(layers):
        if not isinstance(layer, dict):
            raise ValueError('Invalid layer.')
        safe_id(layer.get('id'))
        if layer.get('type')=='image':continue
        role=layer.get('role','artwork')
        if role not in ('artwork',AREA_ROLE,GUIDE_ROLE,*ROLES):raise ValueError('Unknown helper role.')
        if layer.get('visible', True) is False or role!='artwork':
            continue
        visible += 1
        kind = layer.get('type')
        x = number(layer.get('x'), -10000 if helper_mode else -hoop_max, 10000 if helper_mode else 2*hoop_max, 'X position')
        y = number(layer.get('y'), -10000 if helper_mode else -hoop_max, 10000 if helper_mode else 2*hoop_max, 'Y position')
        rotate = number(layer.get('rotation', 0), -360, 360, 'Rotation')
        w = number(layer.get('width'), .2, 10000 if helper_mode else hoop_max, 'Width')
        h = number(layer.get('height'), .2, 10000 if helper_mode else hoop_max, 'Height')
        group = ET.SubElement(root, f'{{{SVG}}}g', id='layer-' + str(i),
                              transform=f'translate({x},{y}) rotate({rotate},{w/2},{h/2}) '
                                        f'translate({w if layer.get("flipX") else 0},{h if layer.get("flipY") else 0}) '
                                        f'scale({-1 if layer.get("flipX") else 1},{-1 if layer.get("flipY") else 1})')
        group.set(f'{{{INK}}}label', str(layer.get('name', kind))[:100])
        group.set(f'{{{INK}}}groupmode', 'layer')
        if kind == 'text':
            generated = lettering(layer.get('lettering', {}))
            # Scaling stitch-font geometry beyond its font-specific limits is
            # rejected. Text sizing goes through the lettering scale control.
            if abs(w - generated['width']) > .05 or abs(h - generated['height']) > .05:
                raise ValueError('Regenerate lettering after changing its font or scale.')
            content = xml(generated['svg'].encode())
            if not layer.get('preserveFontColors',False):paint(content, color(layer['color']))
        elif kind == 'import':
            key = safe_id(layer.get('asset'))
            path = DATA / 'assets' / (key + '.json')
            if not path.exists():
                raise ValueError('An imported SVG asset is missing. Import it again.')
            asset = json.loads(path.read_text())
            content = ET.Element(f'{{{SVG}}}g', transform=f'scale({w/asset["width"]},{h/asset["height"]})')
            content.append(xml(asset['svg'].encode()))
            if layer.get('recolor', False):
                paint(content, color(layer['color']))
            stitch_settings(content, layer)
        elif kind in ('rectangle', 'ellipse', 'path'):
            content = shape_path(layer,helper_mode,hoop_max)
            content = compile_scene_ground(content,layer,editable_project,sys.modules[__name__])
            stitch_settings(content, layer)
            if layer.get('stitch', 'fill') == 'fill' and layer.get('borderEnabled'):
                border_mode = layer.get('borderStitch', 'running')
                if border_mode not in ('running', 'bean', 'zigzag'):
                    raise ValueError('Choose running, bean, or zigzag for the outline.')
                border = shape_path(layer,helper_mode,hoop_max)
                stitch_settings(border, {**layer, 'stitch': border_mode,
                    'color': layer.get('borderColor', '#272829'),
                    'strokeWidth': layer.get('borderWidth', 1.5),
                    'spacing': layer.get('borderSpacing', .4),
                    'stitchLength': layer.get('borderLength', 2.5)})
                wrapper = ET.Element(f'{{{SVG}}}g')
                wrapper.extend([content, border])
                content = wrapper
        else:
            raise ValueError('Unknown layer type.')
        from covered_details import split_pads
        content=split_pads(content,layer,sys.modules[__name__])
        if not streamlines.active(layer):content=compile_small_fills(content,layer,sys.modules[__name__])
        content=streamlines.decorate(content,layer,sys.modules[__name__])
        content=merrow.decorate(content,layer,sys.modules[__name__])
        decorate_fill(root,content,layer,sys.modules[__name__])
        apply_advanced(content,layer)
        content=decorate_multisatin(content,layer,sys.modules[__name__])
        prefix_ids(content, f'l{i}-')
        command_symbols.hide(content)
        marker_symbols.hide(content)
        imported_ignores=[e for e in content.iter(f'{{{SVG}}}use') if command_symbols.name(e.get('{'+command_symbols.XLINK+'}href',''))=='ignore_layer']
        if layer.get('ignoreLayer') is None and imported_ignores and all(any(a.get(f'{{{INK}}}groupmode')=='layer' for a in e.iterancestors()) for e in imported_ignores):
            # Ink/Stitch applies ignore-layer to every containing SVG layer.
            # Our extra wrapper must not expand a nested imported exclusion.
            group.attrib.pop(f'{{{INK}}}groupmode',None)
        group.append(content)
        geometry = [e for e in content.iter() if ET.QName(e).localname in ('path','rect','ellipse','circle','polygon','polyline','line') and not any(ET.QName(a).localname in ('defs','symbol') or re.search(r'display\s*:\s*none',a.get('style','')) for a in [e,*e.iterancestors()])]
        # Ink/Stitch uses the object ID as its default random seed. Native
        # paths need stable IDs so repeated previews and backups agree.
        for j,e in enumerate(geometry):
            if not e.get('id'):e.set('id',f'native-{layer["id"]}-{j}')
            if not e.get(f'{{{STITCH}}}random_seed'):e.set(f'{{{STITCH}}}random_seed',e.get('id'))
        if geometry:
            attach_position_commands(root,group,geometry[0],layer,end_target=geometry[-1])
            # Preserve internal font/import sequencing. Explicit controls apply
            # only at the boundary of the whole layer, including its outline.
            if 'trimAfter' in layer:
                geometry[-1].set(f'{{{STITCH}}}trim_after', str(bool(layer['trimAfter'])))
            if 'stopAfter' in layer:
                geometry[-1].set(f'{{{STITCH}}}stop_after', str(bool(layer['stopAfter'])))
        attach_helpers(root,content,layer,layers,sys.modules[__name__])
        feather.render(root,group,layer,sys.modules[__name__])
        if sewing:
            from covered_details import route as route_covered_details
            route_covered_details(root,group,layer,sys.modules[__name__])
    if not visible:
        raise ValueError('Add at least one visible stitched layer. Reference images and helpers do not sew.')
    # An explicit native value (including None for removal) replaces imported
    # globals. Preserve assets so Undo and other saved designs remain intact.
    from document_cleanup import clear_global
    for key,command in [('origin','origin'),('frameOut','stop_position')]:
        if key in project:clear_global(root,command)
    attach_global_commands(root,project)
    definitions=set()
    for e in list(root.iter()):
        if ET.QName(e).localname in ('marker','symbol') and e.get('id','').startswith(('inkstitch-','inkstitch_')):
            if e.get('id') in definitions:e.getparent().remove(e)
            else:definitions.add(e.get('id'))
    svg_structure.normalize_clone_styles(root)
    command_symbols.settings(project)
    marker_symbols.settings(project)
    stacking_order.settings(project,sys.modules[__name__])
    density_map.settings(project,sys.modules[__name__])
    if sewing and not helper_mode:
        from sewing_optimizer import compile as optimize_sewing
        optimize_sewing(root,project,sys.modules[__name__])
    troubleshoot.settings(project,sys.modules[__name__])
    command_symbols.hide(root)
    if sewing and covered_report:
        from covered_details import validate as validate_covered_details
        validate_covered_details(root,editable_project,covered_report,sys.modules[__name__])
    if sewing and project.get('sewingOptimization',{}).get('enabled',True) and project.get('sewingOptimization',{}).get('manualWaveSnips'):
        from manual_wave_snips import validate as validate_manual_wave_snips
        validate_manual_wave_snips(root,editable_project,sys.modules[__name__])
    return ET.tostring(root, xml_declaration=True, encoding='UTF-8')


